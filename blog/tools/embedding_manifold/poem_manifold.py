#!/usr/bin/env python3
"""Build the real GPT-2 embedding lines for the two short poems.

Run from the repository root:

    uv run --with-requirements blog/tools/embedding_manifold/requirements.txt \
        blog/tools/embedding_manifold/poem_manifold.py
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
from safetensors.numpy import load_file
from tokenizers import Tokenizer

import embedding_manifold as em

DEFAULT_OUT = em.BLOG_ROOT / "poem_manifold_data.js"

POEMS = {
    "en": {
        "sentence": "The fool sees not the same tree that a wise man sees.",
        "author": "William Blake",
        "source": "Proverbs of Hell, The Marriage of Heaven and Hell (c. 1790)",
        "note": "",
    },
    "de": {
        "sentence": "Die Löcher sind das Wichtigste am Sieb.",
        "author": "Joachim Ringelnatz (zugeschrieben)",
        "source": "zugeschrieben, ohne gesicherte Werkangabe",
        "note": "Die Zuschreibung ist verbreitet, aber nicht gesichert.",
    },
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache", type=Path, default=em.DEFAULT_CACHE)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    weights_path, tokenizer_path = em.download_model(args.cache)
    print(f"weights:   {weights_path}")
    print(f"tokenizer: {tokenizer_path}")

    tables = load_file(str(weights_path))
    wte = np.asarray(tables["wte.weight"], dtype=np.float64)
    wpe = np.asarray(tables["wpe.weight"], dtype=np.float64)
    tokenizer = Tokenizer.from_file(str(tokenizer_path))

    data = {
        "model": em.MODEL_ID,
        "modelLabel": "GPT-2 (124M)",
        "dModel": int(wte.shape[1]),
        "positions": int(wpe.shape[0]),
        "poems": {},
    }
    for lang, poem in POEMS.items():
        tokens = em.tokenize(tokenizer, poem["sentence"])
        ids = [token["id"] for token in tokens]
        positions = [token["position"] for token in tokens]
        if max(ids) >= wte.shape[0] or max(positions) >= wpe.shape[0]:
            raise SystemExit("token id or position outside the GPT-2 tables")
        combined = wte[ids] + wpe[positions]
        coords, explained = em.pca3(combined)
        data["poems"][lang] = {
            "sentence": poem["sentence"],
            "author": poem["author"],
            "source": poem["source"],
            "note": poem["note"],
            "tokens": tokens,
            "coords": [[round(float(v), 6) for v in row] for row in coords],
            "explained": [round(float(v), 5) for v in explained],
        }
        print(f"{lang}: {len(tokens)} tokens, explained={data['poems'][lang]['explained']}")

    payload = (
        "/* Generated by blog/tools/embedding_manifold/poem_manifold.py. */\n"
        "window.TM_POEM_MANIFOLD = "
        + json.dumps(data, ensure_ascii=False, indent="\t")
        + ";\n"
    )
    args.out.write_text(payload, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
