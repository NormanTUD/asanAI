#!/usr/bin/env python3
"""Inline the TOKEN / EGO source into one self-contained HTML file.

The source index.html is also usable directly from file:// (classic scripts,
no fetch), but the dist file is the intended artifact: one file, no network,
no server, no build step required by the reader.

Usage:
    python3 tools/build.py
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "index.html"
OUT = ROOT / "dist" / "token-ego.html"


def read(rel: str) -> str:
    p = ROOT / rel
    if not p.exists():
        raise SystemExit(f"missing source file: {p}")
    return p.read_text(encoding="utf-8")


def inline_css(html: str) -> str:
    def repl(m: re.Match) -> str:
        href = m.group(1)
        css = read(href)
        return "<style>\n" + css + "\n</style>"

    return re.sub(r'<link\s+rel="stylesheet"\s+href="([^"]+)"\s*/?>', repl, html)


def inline_scripts(html: str) -> str:
    def repl(m: re.Match) -> str:
        src = m.group(1)
        js = read(src)
        # A literal </script> inside a JS string would close the tag. The
        # escaped form <\/script> is equivalent inside strings and safe here.
        js = js.replace("</script", "<\\/script")
        return '<script data-source="' + src + '">\n' + js + "\n</script>"

    return re.sub(r'<script\s+src="([^"]+)"\s*></script>', repl, html)


def main() -> None:
    html = SRC.read_text(encoding="utf-8")
    html = inline_css(html)
    html = inline_scripts(html)
    banner = (
        "<!--\n"
        "  TOKEN / EGO — a self-contained 3D journey through a transformer.\n"
        "  Generated by tools/build.py from index.html, src/*.js, src/style.css\n"
        "  and the vendored three.js r160 + post-processing passes.\n"
        "  Open this file directly in a browser. No server, no network, no build.\n"
        "  The transformer arithmetic is exact; the attention/FFN weights are a\n"
        "  seeded, structured synthetic checkpoint. See the in-game codex.\n"
        "-->\n"
    )
    if not html.startswith("<!DOCTYPE html>"):
        raise SystemExit("unexpected index.html format")
    html = "<!DOCTYPE html>\n" + banner + html[len("<!DOCTYPE html>"):].lstrip("\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(html, encoding="utf-8")
    size = OUT.stat().st_size
    print(f"wrote {OUT} · {size/1024/1024:.2f} MiB")


if __name__ == "__main__":
    main()
