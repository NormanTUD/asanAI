// Mulberry32 seeded PRNG → deterministic noise per frame
function makeRng(seed) {
	let a = seed >>> 0;
	return () => {
		a = (a + 0x6D2B79F5) >>> 0;
		let t = a;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}
function gauss(rng) {
	let u = 0, v = 0;
	while (u === 0) u = rng();
	while (v === 0) v = rng();
	return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

// Build 21 RGB noisy frames and turn each into a base64 PNG data URL.
function buildColorFrames(cleanImageData, numFrames, seedBase) {
	const out = [];
	const W = cleanImageData.width, H = cleanImageData.height;
	const src = cleanImageData.data;
	for (let s = 0; s < numFrames; s++) {
		const t = s / (numFrames - 1);
		const rng = makeRng(seedBase + s * 7919);
		const canvas = document.createElement('canvas');
		canvas.width = W;
		canvas.height = H;
		const ctx = canvas.getContext('2d');
		const img = ctx.createImageData(W, H);
		const dst = img.data;
		const k = Math.sqrt(1 - t);
		const nk = Math.sqrt(t);
		for (let i = 0; i < src.length; i += 4) {
			const r = src[i] / 255;
			const g = src[i + 1] / 255;
			const b = src[i + 2] / 255;
			const nr = k * r + nk * gauss(rng);
			const ng = k * g + nk * gauss(rng);
			const nb = k * b + nk * gauss(rng);
			dst[i]     = Math.max(0, Math.min(255, nr * 255));
			dst[i + 1] = Math.max(0, Math.min(255, ng * 255));
			dst[i + 2] = Math.max(0, Math.min(255, nb * 255));
			dst[i + 3] = 255;
		}
		ctx.putImageData(img, 0, 0);
		out.push({ url: canvas.toDataURL('image/png'), t });
	}
	return out;
}

