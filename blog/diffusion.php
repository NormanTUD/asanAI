	const range = container.querySelector('input[type="range"]');
	const label = container.querySelector('span');

	const order = reverse ? [...frames].reverse() : frames;

	function fmt(t) {
		if (reverse) return 't = ' + (1 - t).toFixed(2) + '  (denoising)';
		if (t === 0) return 't = 0.00  (clean image)';
		if (t === 1) return 't = 1.00  (pure noise)';
		return 't = ' + t.toFixed(2);
	}

	function update(i) {
		img.src = order[i].url;
		label.textContent = fmt(order[i].t);
	}

	range.addEventListener('input', () => update(parseInt(range.value, 10)));
	update(parseInt(range.value, 10));
}

