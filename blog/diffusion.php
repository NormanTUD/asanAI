## Why does this work? The deep reason

You can train a network to denoise without ever asking "denoise *what*?". But the magic is that, by learning to denoise, the network **also learns the shape of the data distribution itself**. This is the deepest "aha" of diffusion, and it has two equivalent ways of seeing it.

**The coarse-to-fine view.** At the very first denoising steps, the image is almost entirely noise — only the largest-scale structure of the data distribution is recoverable. The network first sketches out rough shapes and color fields, and only later refines fine detail. Generation is hierarchical *by construction*: layout first, then texture, then the tiny highlights on a piece of fruit.

**The score-matching view** \cite[Song & Ermon, 2019]{song2019score}. The denoiser is secretly learning the *score function* — the gradient of the log probability density $\nabla_x \log p(x)$, an arrow that tells you which direction in image-space makes the image more "natural". A particle starting from anywhere and following that arrow (with a little noise for randomness, a recipe called **Langevin dynamics**) drifts toward regions where data actually lives, and ends up looking like a sample from the data distribution.

The two views are mathematically equivalent. Denoising *is* learning the score, and learning the score *is* learning to generate.

The plot below shows the score function for a simple 1D "data distribution" that has two peaks (a bimodal distribution, like a mixture of two Gaussians). The blue curve is the density $p(x)$, the red curve is the score $\nabla_x \log p(x)$. Notice that the score **crosses zero exactly at the peaks** — those are the points the data likes to live at — and points outward away from the valleys between peaks. Drag the slider to drop a particle anywhere; it follows the score and ends up at one of the peaks.
