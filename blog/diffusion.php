// SCORE-MATCHING VIZ
// 1D bimodal density + score function, plus a draggable particle
// =============================================================================
function makeScoreViz(containerId) {
	const xs = [];
	const dx = 0.02;
	for (let x = -4.5; x <= 4.5; x += dx) xs.push(x);

	const mu1 = -1.6, mu2 = 1.6, sigma = 0.85;
	const gaussPdf = (x, mu) => Math.exp(-0.5 * Math.pow((x - mu) / sigma, 2)) / (sigma * Math.sqrt(2 * Math.PI));
	const p = (x) => 0.5 * gaussPdf(x, mu1) + 0.5 * gaussPdf(x, mu2);
	const dp = (x) => 0.5 * gaussPdf(x, mu1) * (-(x - mu1) / (sigma * sigma))
	             + 0.5 * gaussPdf(x, mu2) * (-(x - mu2) / (sigma * sigma));
	const score = (x) => dp(x) / p(x);

	const pTrace = {
		x: xs, y: xs.map(p), mode: 'lines', name: 'p(x)  data density',
		line: { color: '#3b82f6', width: 2.5 }, yaxis: 'y'
	};
	const sTrace = {
		x: xs, y: xs.map(score), mode: 'lines', name: '∇ₓ log p(x)  score',
		line: { color: '#ef4444', width: 2.5 }, yaxis: 'y2'
	};

	// Arrows on the score subplot: where the score points
	const arrowXs = [];
	for (let x = -4; x <= 4; x += 0.4) arrowXs.push(x);
	const shapes = arrowXs.map((x) => {
		const s = score(x);
		const head = 0.18 * Math.sign(s);
		return {
			type: 'line',
			xref: 'x2', yref: 'y2',
			x0: x, x1: x,
			y0: 0, y1: Math.max(-2.5, Math.min(2.5, s)),
			line: { color: s > 0 ? '#22c55e' : '#a855f7', width: 2 },
			arrowhead: 3, arrowsize: 1, arrowwidth: 1.5
		};
	});

	// Particle: starts at x = -3.5
	let particleX = -3.5;
	const particleTrace = {
		x: [particleX], y: [p(particleX)],
		mode: 'markers+text', name: 'sample x',
		marker: { size: 14, color: '#f59e0b', line: { color: '#92400e', width: 2 } },
		text: ['drag me'], textposition: 'top center',
		textfont: { color: themeFg, size: 11 },
		yaxis: 'y'
	};

	const layout = plotlyLayout({
		grid: { rows: 2, columns: 1, pattern: 'independent' },
		title: { text: 'Score function: arrows point toward where data lives', font: { size: 13 } },
		shapes: shapes,
		xaxis: { title: 'x', range: [-4.5, 4.5] },
		yaxis: { title: 'p(x)', rangemode: 'tozero' },
		xaxis2: { title: 'x', range: [-4.5, 4.5] },
		yaxis2: { title: 'score', range: [-3, 3], zeroline: true, zerolinecolor: themeFg, zerolinewidth: 1 },
		legend: { x: 1.02, y: 1, xanchor: 'left' },
		showlegend: true,
		margin: { t: 50, b: 50, l: 60, r: 140 },
		dragmode: 'pan'
	});

	Plotly.newPlot(containerId, [pTrace, sTrace, particleTrace], layout, { responsive: true, displayModeBar: false }).then((gd) => {
		// Click-to-place or drag the particle
		gd.on('plotly_click', (ev) => {
			if (!ev.points || !ev.points.length) return;
			const pt = ev.points[0];
			if (pt.yaxis !== undefined && pt.yaxis.title && pt.yaxis.title.text && pt.yaxis.title.text.startsWith('p(')) {
				particleX = Math.max(-4.3, Math.min(4.3, pt.x));
				Plotly.restyle(containerId, { x: [[particleX]], y: [[p(particleX)]] }, [2]);
			}
		});

		// "Run Langevin" button: step the particle 200 times along the score
		const btn = document.createElement('button');
		btn.textContent = '▶ Run Langevin dynamics (200 steps)';
		btn.style.cssText = 'margin:8px auto; display:block; padding:8px 16px; background:var(--mn-accent,#3b82f6); color:#fff; border:none; border-radius:6px; cursor:pointer; font:inherit;';
		btn.onclick = async () => {
			btn.disabled = true;
			btn.textContent = 'Following the score…';
			let x = particleX;
			const dt = 0.05;
			const noiseScale = 0.35;
			for (let step = 0; step < 200; step++) {
				const s = score(x);
				x = x + s * dt + noiseScale * Math.sqrt(2 * dt) * gauss(makeRng(step * 991 + 7));
				if (Math.abs(x) > 4.3) x = Math.sign(x) * 4.3;
				particleX = x;
				Plotly.restyle(containerId, { x: [[x]], y: [[p(x)]] }, [2]);
				if (step % 4 === 0) await new Promise(r => setTimeout(r, 12));
			}
			btn.textContent = '↻ Try again from a different starting point';
			btn.disabled = false;
		};
		gd.parentNode.insertBefore(btn, gd.nextSibling);
	});
}

