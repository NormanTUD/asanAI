// Mulberry32 seeded PRNG → deterministic noise per frame
function makeRng(seed) {
	let a = seed >>> 0;
	return () => {
		a = (a + 0x6D2B79F5) >>> 0;
		let t = a;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}
function gauss(rng) {
	let u = 0, v = 0;
	while (u === 0) u = rng();
	while (v === 0) v = rng();
	return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

function buildNoiseFrames(clean, seedBase) {
	const frames = [];
	for (let s = 0; s <= 10; s++) {
		const t = s / 10;
		const rng = makeRng(seedBase + s);
		const z = [];
		for (let y = 0; y < GRID; y++) {
			const row = [];
			for (let x = 0; x < GRID; x++) {
				const idx = y * GRID + x;
				const n = gauss(rng);
				row.push(Math.sqrt(1 - t) * clean[idx] + Math.sqrt(t) * n);
			}
			z.push(row);
		}
		frames.push({ z, t });
	}
	return frames;
}

